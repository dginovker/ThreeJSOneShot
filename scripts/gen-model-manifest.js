// Regenerates src/models.generated.js from whatever glTF sit in public/models.
// Run after adding or removing an asset pack: node scripts/gen-model-manifest.js
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = 'public/models';
const paths = {};

for (const category of readdirSync(ROOT, { withFileTypes: true })) {
  if (!category.isDirectory()) continue;
  for (const file of readdirSync(join(ROOT, category.name))) {
    if (!file.endsWith('.gltf')) continue;
    const name = file.slice(0, -5);
    const path = `${category.name}/${file}`;
    // The pack ships two models in a second category; they are byte-identical,
    // so whichever is seen first wins.
    paths[name] ??= path;
  }
}

const entries = Object.keys(paths).sort().map((n) => `  ${n}: '${paths[n]}',`);
writeFileSync(
  'src/models.generated.js',
  `// Generated by scripts/gen-model-manifest.js — do not edit.\n` +
    `export const MODEL_PATHS = {\n${entries.join('\n')}\n};\n`
);
console.log(`wrote src/models.generated.js — ${entries.length} models`);
